"""Mathematical convergence study for the adaptive testing engine.

Simulates examinees with known true theta answering exams generated by
different selection strategies, then reports bias / RMSE / correlation /
SEM trajectories — the "đánh giá toán học về độ hội tụ năng lực" deliverable.

Strategies:
  - rules  : the real exam-batch engine (generate_exam, R1-R12)
  - fisher : per exam, pick N items with max Fisher information at theta-hat
  - random : per exam, N random unused items

Usage (inside backend container):
  python -m app.evaluation.convergence --subject 2 --students 30
"""
import argparse
import asyncio
import math
import random as _random

from sqlalchemy.ext.asyncio import AsyncSession

from app.config import get_settings
from app.engine.irt import probability_3pl, information_3pl, estimate_ability_3pl
from app.models.user import ExamChain
from app.services.exam_generation import generate_exam, _load_candidate_pool

SIM_LLM_SETTINGS = {"llm_enabled": False, "cat_enable_hybrid_llm_on_answer": False}
SIM_USER_ID = -1  # never exists in DB -> no cross-session history


def _simulate_answer(rng: _random.Random, true_theta: float, q: dict) -> bool:
    p = probability_3pl(true_theta, q["a"], q["b"], q["c"])
    return rng.random() < p


def _q_dict(q) -> dict:
    """Normalize a Question ORM object or pool dict to {a, b, c, id, topic_id}."""
    if isinstance(q, dict):
        return {
            "id": q["id"],
            "topic_id": q["topic_id"],
            "a": float(q["discrimination_a"]),
            "b": float(q["difficulty_b"]),
            "c": float(q["guessing_c"]),
            "question_type": q.get("question_type"),
            "topic_name": q.get("topic_name", ""),
        }
    return {
        "id": q.id,
        "topic_id": q.topic_id,
        "a": float(q.discrimination_a),
        "b": float(q.difficulty_b),
        "c": float(q.guessing_c),
        "question_type": q.question_type,
        "topic_name": q.topic.name if q.topic else "",
    }


async def _pick_exam(
    db: AsyncSession,
    strategy: str,
    *,
    subject_id: int,
    pool: list[dict],
    used_ids: set[int],
    exam_index: int,
    theta: float,
    sem: float,
    chain_scoring_data: list[dict],
    prev_exam_scoring_data: list[dict],
    questions_per_exam: int,
    rng: _random.Random,
    b_target_override: float | None = None,
) -> list[dict]:
    unused = [q for q in pool if q["id"] not in used_ids]
    if not unused:
        return []

    if strategy == "random":
        picked = rng.sample(unused, min(questions_per_exam, len(unused)))
        return [_q_dict(q) for q in picked]

    if strategy == "fisher":
        ranked = sorted(
            unused,
            key=lambda q: -information_3pl(
                theta, float(q["discrimination_a"]), float(q["difficulty_b"]), float(q["guessing_c"])
            ),
        )
        return [_q_dict(q) for q in ranked[:questions_per_exam]]

    # "rules" (and "rl" which reuses the rule engine with a b_target override)
    chain = ExamChain(
        user_id=SIM_USER_ID,
        subject_id=subject_id,
        questions_per_exam=questions_per_exam,
        max_exams=99,
        recognition_pct=0.3,
        comprehension_pct=0.5,
        application_pct=0.2,
    )
    questions, _events = await generate_exam(
        db,
        chain=chain,
        user_id=SIM_USER_ID,
        exam_index=exam_index,
        theta=theta,
        sem=sem,
        chain_scoring_data=chain_scoring_data,
        prev_exam_scoring_data=prev_exam_scoring_data,
        used_question_ids=set(used_ids),
        used_signatures=set(),
        llm_runtime_settings=SIM_LLM_SETTINGS,
        b_target_override=b_target_override,
    )
    return [_q_dict(q) for q in questions]


async def simulate_student(
    db: AsyncSession,
    strategy: str,
    *,
    subject_id: int,
    pool: list[dict],
    true_theta: float,
    questions_per_exam: int,
    max_exams: int,
    rng: _random.Random,
    sem_stop: float,
    policy=None,
) -> dict:
    """Run one simulated student through the multi-stage flow."""
    used_ids: set[int] = set()
    chain_scoring: list[dict] = []
    prev_scoring: list[dict] = []
    theta, sem = 0.0, 999.0
    sem_trajectory: list[float] = []
    theta_trajectory: list[float] = []
    rl_transitions: list[dict] = []

    for exam_index in range(1, max_exams + 1):
        b_override = None
        rl_state = rl_action = None
        if strategy == "rl" and policy is not None and exam_index > 1:
            prev_acc = (
                sum(1 for r in prev_scoring if r["is_correct"]) / len(prev_scoring)
                if prev_scoring
                else 0.0
            )
            rl_state = policy.state_key(prev_acc, sem)
            rl_action = policy.select_action(rl_state)
            b_override = max(-3.0, min(3.0, theta + policy.actions[rl_action]))

        questions = await _pick_exam(
            db,
            "rules" if strategy == "rl" else strategy,
            subject_id=subject_id,
            pool=pool,
            used_ids=used_ids,
            exam_index=exam_index,
            theta=theta,
            sem=sem,
            chain_scoring_data=chain_scoring,
            prev_exam_scoring_data=prev_scoring,
            questions_per_exam=questions_per_exam,
            rng=rng,
            b_target_override=b_override,
        )
        if not questions:
            break

        prev_scoring = []
        for q in questions:
            correct = _simulate_answer(rng, true_theta, q)
            row = {
                "a": q["a"],
                "b": q["b"],
                "c": q["c"],
                "is_correct": correct,
                "topic_id": q["topic_id"],
                "topic_name": q.get("topic_name", ""),
                "question_type": q.get("question_type"),
                "guessing_flag": False,
            }
            chain_scoring.append(row)
            prev_scoring.append(row)
            used_ids.add(q["id"])

        prev_sem = sem
        ability = estimate_ability_3pl(chain_scoring)
        theta = float(ability["theta_map"])
        sem = float(ability["posterior_sd"])
        theta_trajectory.append(round(theta, 4))
        sem_trajectory.append(round(sem, 4))

        if strategy == "rl" and rl_state is not None:
            reward = (prev_sem if prev_sem < 999 else 1.0) - sem
            rl_transitions.append({"state": rl_state, "action": rl_action, "reward": reward})
            policy.update(rl_state, rl_action, reward)

        if sem < sem_stop:
            break

    return {
        "true_theta": true_theta,
        "theta_hat": theta,
        "error": theta - true_theta,
        "items_used": len(chain_scoring),
        "exams_used": len(sem_trajectory),
        "converged": sem < sem_stop,
        "final_sem": sem,
        "sem_trajectory": sem_trajectory,
        "theta_trajectory": theta_trajectory,
        "rl_transitions": rl_transitions,
    }


def _aggregate(strategy: str, results: list[dict], max_exams: int) -> dict:
    n = len(results)
    errors = [r["error"] for r in results]
    bias = sum(errors) / n
    rmse = math.sqrt(sum(e * e for e in errors) / n)
    mae = sum(abs(e) for e in errors) / n

    # Pearson correlation between true theta and estimate
    xs = [r["true_theta"] for r in results]
    ys = [r["theta_hat"] for r in results]
    mx, my = sum(xs) / n, sum(ys) / n
    cov = sum((x - mx) * (y - my) for x, y in zip(xs, ys))
    vx = math.sqrt(sum((x - mx) ** 2 for x in xs))
    vy = math.sqrt(sum((y - my) ** 2 for y in ys))
    corr = cov / (vx * vy) if vx > 0 and vy > 0 else 0.0

    # Mean SEM after each exam (only over students who reached that exam)
    mean_sem_by_exam = []
    for k in range(max_exams):
        vals = [r["sem_trajectory"][k] for r in results if len(r["sem_trajectory"]) > k]
        if vals:
            mean_sem_by_exam.append(round(sum(vals) / len(vals), 4))

    converged = [r for r in results if r["converged"]]
    return {
        "strategy": strategy,
        "n_students": n,
        "bias": round(bias, 4),
        "rmse": round(rmse, 4),
        "mae": round(mae, 4),
        "correlation": round(corr, 4),
        "convergence_rate": round(len(converged) / n, 4),
        "mean_items_used": round(sum(r["items_used"] for r in results) / n, 2),
        "mean_items_to_converge": round(
            sum(r["items_used"] for r in converged) / len(converged), 2
        )
        if converged
        else None,
        "mean_sem_by_exam": mean_sem_by_exam,
        "students": [
            {
                "true_theta": round(r["true_theta"], 3),
                "theta_hat": round(r["theta_hat"], 3),
                "error": round(r["error"], 3),
                "items_used": r["items_used"],
                "converged": r["converged"],
                "final_sem": round(r["final_sem"], 3),
            }
            for r in results
        ],
    }


async def run_convergence_study(
    db: AsyncSession,
    subject_id: int,
    *,
    n_students: int = 30,
    questions_per_exam: int = 6,
    max_exams: int = 5,
    strategies: tuple[str, ...] = ("rules", "fisher", "random"),
    seed: int = 42,
    policy=None,
) -> dict:
    settings = get_settings()
    sem_stop = float(settings.ADAPTIVE_SEM_STOP)

    pool = await _load_candidate_pool(db, subject_id)
    if len(pool) < questions_per_exam:
        raise ValueError(f"Question bank too small: {len(pool)} items")

    # Deterministic spread of true abilities across the theta scale
    if n_students == 1:
        true_thetas = [0.0]
    else:
        true_thetas = [-2.5 + i * 5.0 / (n_students - 1) for i in range(n_students)]

    report: dict = {
        "subject_id": subject_id,
        "n_students": n_students,
        "questions_per_exam": questions_per_exam,
        "max_exams": max_exams,
        "sem_stop": sem_stop,
        "pool_size": len(pool),
        "strategies": [],
    }

    for strategy in strategies:
        results = []
        for i, tt in enumerate(true_thetas):
            rng = _random.Random(seed * 1000 + i)
            results.append(
                await simulate_student(
                    db,
                    strategy,
                    subject_id=subject_id,
                    pool=pool,
                    true_theta=tt,
                    questions_per_exam=questions_per_exam,
                    max_exams=max_exams,
                    rng=rng,
                    sem_stop=sem_stop,
                    policy=policy if strategy == "rl" else None,
                )
            )
        report["strategies"].append(_aggregate(strategy, results, max_exams))

    return report


def format_report(report: dict) -> str:
    lines = [
        f"Convergence study | subject={report['subject_id']} pool={report['pool_size']} "
        f"| {report['n_students']} students x {report['max_exams']} exams x "
        f"{report['questions_per_exam']} items | stop SEM<{report['sem_stop']}",
        "",
        f"{'strategy':<10}{'bias':>8}{'RMSE':>8}{'MAE':>8}{'corr':>8}{'conv%':>8}{'items':>8}",
    ]
    for s in report["strategies"]:
        lines.append(
            f"{s['strategy']:<10}{s['bias']:>8.3f}{s['rmse']:>8.3f}{s['mae']:>8.3f}"
            f"{s['correlation']:>8.3f}{s['convergence_rate'] * 100:>7.1f}%{s['mean_items_used']:>8.1f}"
        )
    lines.append("")
    for s in report["strategies"]:
        lines.append(f"  SEM by exam ({s['strategy']}): {s['mean_sem_by_exam']}")
    return "\n".join(lines)


async def _main():
    from app.database import async_session

    parser = argparse.ArgumentParser()
    parser.add_argument("--subject", type=int, default=2)
    parser.add_argument("--students", type=int, default=30)
    parser.add_argument("--per-exam", type=int, default=6)
    parser.add_argument("--max-exams", type=int, default=5)
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()

    async with async_session() as db:
        report = await run_convergence_study(
            db,
            args.subject,
            n_students=args.students,
            questions_per_exam=args.per_exam,
            max_exams=args.max_exams,
            seed=args.seed,
        )
    print(format_report(report))


if __name__ == "__main__":
    asyncio.run(_main())
